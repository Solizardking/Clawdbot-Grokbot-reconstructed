import { chromium } from 'playwright';
import assert from 'node:assert/strict';
const browser = await chromium.launch({ headless: true });
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
try {
const failures = [];
page.on('pageerror', error => failures.push(error.message));
await page.addInitScript(() => { localStorage.setItem('omb-email-gate', 'skipped'); localStorage.setItem('omb-analytics-opt-out', '1'); if (!localStorage.getItem('clawd-skin')) localStorage.setItem('clawd-skin', 'atelier'); });
let relay;
await page.routeWebSocket('wss://clawd-ws.fly.dev/ws', ws => { relay = ws; ws.send(JSON.stringify({ type: 'status', connected: true })); });
await page.goto(process.env.CLAWD_SMOKE_URL || 'http://127.0.0.1:5299');
await page.getByRole('button', { name: 'Solana mode', exact: true }).click();
const panel = page.getByRole('complementary', { name: 'Solana workspace' });
await panel.waitFor();
assert.equal(await page.locator('html').getAttribute('data-skin'), 'solana');
const token = { type: 'token-launch', mint: 'So11111111111111111111111111111111111111112', name: 'QA launch', symbol: 'QA', marketCapSol: 0, hasGithub: true };
relay.send(JSON.stringify(token));
await page.getByRole('heading', { name: 'QA launch' }).waitFor();
await page.getByLabel('Search tokens by name, symbol or mint').fill('missing');
await page.getByText('No matching launches', { exact: true }).waitFor();
await page.getByLabel('Search tokens by name, symbol or mint').fill('');
await page.getByRole('button', { name: 'Pause', exact: true }).click();
relay.send(JSON.stringify({ ...token, name: 'Skipped launch' }));
await page.waitForTimeout(100);
assert.equal(await page.getByRole('heading', { name: 'Skipped launch' }).count(), 0);
await page.getByRole('button', { name: 'Resume', exact: true }).click();
await page.getByRole('tab', { name: 'Wallets & assets' }).click();
await page.getByLabel('Solana owner address').waitFor();
await page.getByRole('tab', { name: 'Pump.fun', exact: true }).click();
await page.screenshot({ path: '/tmp/clawd-solana-desktop.png' });
await page.getByRole('switch').click();
assert.equal(await page.locator('html').getAttribute('data-skin'), 'atelier');
await page.getByRole('switch').click();
await page.getByRole('button', { name: 'Close Solana workspace' }).click();
await page.getByRole('button', { name: 'Pump.fun tokens', exact: true }).click();
await page.setViewportSize({ width: 390, height: 844 });
assert.ok((await panel.boundingBox()).width <= 390);
assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
await page.screenshot({ path: '/tmp/clawd-solana-mobile.png' });
await page.getByRole('button', { name: 'Close Solana workspace' }).press('Escape');
assert.equal(await panel.count(), 0);
await page.reload();
await panel.waitFor();
assert.equal(await page.locator('html').getAttribute('data-skin'), 'solana');
await page.getByRole('switch').click();
assert.equal(await page.locator('html').getAttribute('data-skin'), 'atelier');
assert.deepEqual(failures, []);
console.log('Solana workspace passed: native feed, search, pause, wallet view, theme restore, close/reopen, mobile, Escape.');

} finally { await browser.close(); }
